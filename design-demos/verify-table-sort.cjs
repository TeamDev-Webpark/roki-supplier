'use strict';
/* Column headers sort every list table; a paginated table is sorted across all pages. */
const {run,login,assert}=require('./_env.cjs');
run('sortable table headers',async({base,context})=>{
  const p=await context.newPage();await login(p,base,'roki','r-issue','request-register');
  const col=()=>p.locator('table.desk-table tbody tr').evaluateAll(r=>r.map(x=>x.cells[0].innerText.split('\n')[0]));
  const head=p.locator('table.desk-table th .th-sort').first();
  assert(await head.count(),'Headers have a sort control');
  await head.click();const asc=await col();assert(asc.length>12,'Sorting shows every row, not only the first page');
  assert.deepEqual(asc,asc.slice().sort((a,b)=>a.localeCompare(b,undefined,{numeric:true,sensitivity:'base'})));
  await p.locator('table.desk-table th .th-sort').first().click();const desc=await col();assert.deepEqual(desc,asc.slice().reverse());
  assert.equal(await p.locator('table.desk-table th[aria-sort="descending"]').count(),1);
  await p.locator('table.desk-table th .th-sort').first().click();assert.equal(await p.locator('table.desk-table th[aria-sort="none"]').count()>0,true);
  await p.goto(base+'roki.html#parts');
  const catalog=p.locator('table[data-sort-page="parts"]');
  const codes=()=>catalog.locator('tbody tr td:first-child a').allTextContents();
  const expected=await p.evaluate(()=>currentItems().map(item=>item.code).sort((a,b)=>a.localeCompare(b,undefined,{numeric:true,sensitivity:'base'})));
  await catalog.locator('th .th-sort').first().click();
  assert.deepEqual(await codes(),expected.slice(0,12));
  await p.locator('[data-desk-key="parts"][data-desk-page="2"]').click();
  assert.deepEqual(await codes(),expected.slice(12,24),'Sorting is applied before slicing the next page');
  await p.locator('#search').fill(expected.at(-1));
  assert.equal(await p.evaluate(()=>deskState('parts').page),1,'Searching restarts pagination');
  assert((await codes()).includes(expected.at(-1)),'Search reaches records outside the current page');
  await p.locator('#search').fill('');
  await p.locator('[data-desk-key="parts"][data-desk-page="2"]').click();
  await p.locator('#format-filter').selectOption('Assembly');
  assert.equal(await p.evaluate(()=>deskState('parts').page),1,'Changing format restarts pagination');
  assert((await catalog.locator('tbody tr td:nth-child(3)').allTextContents()).every(text=>text.startsWith('Assembly')));
  await p.setViewportSize({width:390,height:844});
  assert(await p.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'Catalog pager stays within the mobile viewport');
  await p.setViewportSize({width:1500,height:1100});
  await p.goto(base+'roki.html#quotes');
  const quoteRows=p.locator('.desk-quotes-table tbody tr');
  const quoteIds=()=>quoteRows.evaluateAll(rows=>rows.map(row=>row.dataset.open));
  const original=await quoteIds();
  const sample=await p.evaluate(()=>visibleQuotes().find(q=>q.status==='Approved'&&priceValidity(q)==='active'&&q.effective&&q.total>0));
  assert(sample);
  await p.locator('[data-active-quote-toggle]').click();
  const filters=p.locator('#active-quote-advanced');
  await filters.locator('[name="minPrice"]').fill('100');
  await filters.locator('[name="maxPrice"]').fill('1');
  await filters.locator('[type="submit"]').click();
  assert(await filters.locator('[role="alert"]').isVisible());
  assert.deepEqual(await quoteIds(),original,'Invalid filters do not replace the results');
  await p.locator('#supplier-filter').selectOption(sample.supplier);
  await filters.locator('[name="format"]').selectOption(sample.format);
  await filters.locator('[name="effectiveFrom"]').fill(sample.effective);
  await filters.locator('[name="effectiveTo"]').fill(sample.effective);
  await filters.locator('[name="minPrice"]').fill(String(sample.total));
  await filters.locator('[name="maxPrice"]').fill(String(sample.total));
  await filters.locator('[type="submit"]').click();
  const expectedQuotes=await p.evaluate(s=>visibleQuotes().filter(q=>q.status==='Approved'&&priceValidity(q)==='active'&&q.supplier===s.supplier&&q.format===s.format&&q.effective===s.effective&&q.total===s.total).map(q=>q.id).reverse(),sample);
  assert.deepEqual(await quoteIds(),expectedQuotes.slice(0,12));
  await p.locator('[data-active-quote-clear]').click();
  assert.deepEqual(await quoteIds(),original);
  await p.locator('.desk-quotes-table th .th-sort').first().click();
  assert.equal(await quoteRows.count(),12,'Quotation sorting retains pagination');
  await p.locator('[data-desk-key="quote-register"][data-desk-page="2"]').click();
  assert.equal(await p.evaluate(()=>deskState('quote-register').page),2);
  await p.setViewportSize({width:390,height:844});
  assert(await p.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'Advanced quote filters stay within the mobile viewport');
  await p.setViewportSize({width:1500,height:1100});
  /* editing tables keep plain headers */
  await login(p,base,'roki','r-approve','formulas');assert.equal(await p.locator('.fm-table th .th-sort').count(),0);
});
